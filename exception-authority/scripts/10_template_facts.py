#!/usr/bin/env python3
"""Step 10 (post hoc, descriptive; added 18 Nov 2026 after the main-stage data were read). Results per
scenario template, into results/template-facts.md (shipped in the anonymous export since 19 Nov 2026).
See src/exception_authority/templates.py for the definitions. Computes no statistic.

Usage: python scripts/10_template_facts.py [--out FILE]
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))  # works without `pip install -e .`

from exception_authority import outputs, paths  # noqa: E402
from exception_authority import scenarios as S  # noqa: E402
from exception_authority import templates as T  # noqa: E402

FLAG = "**single template**"


def frac(k_n):
    k, n = k_n
    return f"{k}/{n}" if n else "-"


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=paths.RESULTS / "template-facts.md")
    args = ap.parse_args(argv)
    cfg = outputs.config()
    scen = T.scenarios_by_id(paths.SCENARIOS)
    panel_out = cfg["stages"]["main"].get("outside_panel", [])
    tpls = T.templates(scen, "main")
    btpl = T.base_template(scen, "main")
    btpl_imp = T.base_template(scen, "main-implicit")
    # implicit ids end in -implicit and share base names with an -implicit suffix; map both stages to templates
    names = [T.template_name(t) for t in tpls]
    lines = [
        "# Results per scenario template (post hoc, descriptive)",
        "",
        "Generated by `exception-authority/scripts/10_template_facts.py` from the sample-1 rows in "
        "`results/main/` and `results/main-implicit/`, with the scorer's own definitions of a valid reply and of "
        "acceptance. Added on 18 Nov 2026, after the main-stage data were read; not part of the registered analysis "
        "(logged in `results/logs/deviations.md`). No statistic is computed.",
        "",
        f"The {len(btpl)} main base scenarios come from {len(tpls)} templates, one per domain and direction; within a "
        "template the base scenarios differ only in one noun (the product or item). A template **accepts** a cell when "
        "more than half of its valid variants accept, and **refuses** it when fewer than half do. An effect is flagged "
        f"{FLAG} when one template holds at least {int(T.SINGLE_SHARE * 100)}% of the events that make it up.",
        "",
        "Templates: " + "; ".join(f"T{i + 1} = {n}" for i, n in enumerate(names)) + ".",
        "",
    ]
    stages = [("main", btpl), ("main-implicit", btpl_imp)]
    decs = {}
    for stage, bt in stages:
        e = outputs.load_json(paths.RESULTS / stage / "effects.json") or {}
        models = list(e.get("models", {})) or cfg["stages"][stage]["models"]   # Table 2 order
        lines += [f"## Acceptance per template: {stage}", ""]
        for m in models:
            dec = T.decisions(paths.RESULTS, stage, m, scen)
            decs[(stage, m)] = dec
            per = T.per_template(dec, bt)
            label = outputs.model_label(m) + (" (outside the panel)" if m in panel_out else "")
            lines += [f"### {label}", "",
                      "| Cell | " + " | ".join(f"T{i + 1}" for i in range(len(tpls))) + " | templates accepting | refusing |",
                      "|---|" + "---|" * len(tpls) + "---|---|"]
            for cell in S.CELLS:
                row = [frac(per[cell][t]) for t in tpls]
                lines.append(f"| {cell} | " + " | ".join(row)
                             + f" | {T.count(per, cell, 'accept', tpls)} | {T.count(per, cell, 'refuse', tpls)} |")
            lines.append("")

    def per(stage, m):
        return T.per_template(decs[(stage, m)], btpl if stage == "main" else btpl_imp)

    eff = outputs.load_json(paths.RESULTS / "main" / "effects.json") or {}
    main_models = list(eff.get("models", {})) or cfg["stages"]["main"]["models"]   # Table 2 order
    lines += ["## Key patterns (templates out of %d)" % len(tpls), "",
              "| Model | D accepted | D refused | B-out rejected | A accepted |", "|---|---|---|---|---|"]
    for m in main_models:
        p = per("main", m)
        lines.append(f"| {outputs.model_label(m)} | {T.count(p, 'D', 'accept', tpls)} | {T.count(p, 'D', 'refuse', tpls)} "
                     f"| {T.count(p, 'B-out', 'refuse', tpls)} | {T.count(p, 'A', 'accept', tpls)} |")
    lines.append("")

    def events_line(title, events_by_t, total_word):
        ev = {t: events_by_t.get(t, 0) for t in tpls}
        total, top, single = T.concentration(ev)
        cells = " | ".join(str(ev[t]) for t in tpls)
        flag = f" {FLAG} ({T.template_name(top)}: {ev[top]} of {total})" if single else ""
        return f"| {title} | {cells} | {total} {total_word}{flag} |"

    head = "| Effect | " + " | ".join(f"T{i + 1}" for i in range(len(tpls))) + " | total |"
    sep = "|---|" + "---|" * len(tpls) + "---|"

    lines += ["## Concentration of reported effects", "",
              "Event counts per template; the last column flags effects in which one template holds at least "
              f"{int(T.SINGLE_SHARE * 100)}% of the events. For one template, the H1 difference C-ctl minus C-no is "
              "(C-ctl only minus C-no only) divided by that template's pairs with valid replies in both cells "
              "(the denominators of the C-ctl and C-no rows above).", "", head, sep]
    for m in main_models:  # H1: base scenarios accepting C-ctl but not C-no
        d = T.discordant(decs[("main", m)], btpl, "C-ctl", "C-no")
        lines.append(events_line(f"H1 discordant pairs (C-ctl only), {outputs.model_label(m)}",
                                 {t: d[t][0] for t in tpls}, "pairs"))
        lines.append(events_line(f"H1 discordant pairs (C-no only), {outputs.model_label(m)}",
                                 {t: d[t][1] for t in tpls}, "pairs"))
    for m in main_models:  # the negation control: C-ok accepted but not C-ctl
        d = T.discordant(decs[("main", m)], btpl, "C-ok", "C-ctl")
        if sum(v[0] + v[1] for v in d.values()):
            lines.append(events_line(f"Control C-ok only (vs C-ctl), {outputs.model_label(m)}",
                                     {t: d[t][0] for t in tpls}, "pairs"))
    for m in main_models:  # acceptances in B-out and in A
        p = per("main", m)
        for cell in ("B-out", "A"):
            ev = {t: p[cell][t][0] for t in tpls}
            if sum(ev.values()) and m.startswith(("claude-", "llama")):
                lines.append(events_line(f"{cell} acceptances, {outputs.model_label(m)}", ev, "acceptances"))
    e_imp = outputs.load_json(paths.RESULTS / "main-implicit" / "effects.json") or {}
    imp_models = list(e_imp.get("models", {})) or cfg["stages"]["main-implicit"]["models"]
    rows_imp = []
    for m in imp_models:
        # pair explicit and implicit decisions by base scenario: implicit bases carry the -implicit suffix
        e = decs[("main", m)]
        i = {(b.removesuffix("-implicit"), c): v for (b, c), v in decs[("main-implicit", m)].items()}
        r = T.rises(e, i, btpl, "D")
        rows_imp.append(events_line(f"Implicit-arm rise in D (accepted only without the rule), {outputs.model_label(m)}",
                                    {t: r[t][0] for t in tpls}, "base scenarios"))
        p_i = T.per_template(i, btpl)
        rows_imp.append(f"| Templates accepting D without the rule, {outputs.model_label(m)} | "
                        + " | ".join(frac(p_i['D'][t]) for t in tpls)
                        + f" | {T.count(p_i, 'D', 'accept', tpls)} of {len(tpls)} |")
    lines += rows_imp + [""]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
